import org.gradle.internal.classpath.Instrumented.systemProperty

plugins {
    `java-library`
    eclipse
    idea
    `maven-publish`
    id("net.neoforged.moddev")
    id("me.modmuss50.mod-publish-plugin")
}

val minecraft_version = property("minecraft_version") as String
val minecraft_version_range = property("minecraft_version_range") as String
val neo_version = property("neo_version") as String
val mod_id = property("mod_id") as String
val mod_group_id = property("mod_group_id") as String
val mod_name = property("mod_name") as String
val mod_license = property("mod_license") as String
val mod_version = property("mod_version") as String
val mod_authors = property("mod_authors") as String
val mod_description = property("mod_description") as String

val mainSourceSet = sourceSets.main.get()

version = "$mod_version-neoforge-$minecraft_version"
group = mod_group_id

base {
    archivesName = mod_id
}

// Mojang ships Java 25 to end users in 26.1, so your mod should target Java 25.
java.toolchain.languageVersion = JavaLanguageVersion.of(25)

neoForge {
    version = neo_version

    runs {
        create("client") {
            client()
            gameDirectory = file("run/client")
            programArguments = listOf(
                "--username", "steve"
            )
            systemProperty("neoforge.enabledGameTestNamespaces", mod_id)
        }

        create("server") {
            server()
            gameDirectory = file("run/server")
            programArgument("--nogui")
            systemProperty("neoforge.enabledGameTestNamespaces", mod_id)
        }

        create("gameTestServer") {
            type = "gameTestServer"
            systemProperty("neoforge.enabledGameTestNamespaces", mod_id)
        }

        create("data") {
            clientData()
            gameDirectory = file("run/data")
            programArguments.addAll(
                "--mod", mod_id, "--all",
                "--output", file("src/generated/resources/").absolutePath,
                "--existing", file("src/main/resources/").absolutePath
            )
            // 临时：定位注册表初始化阶段的 ExceptionInInitializerError
            jvmArguments.add("-Xlog:class+init=info:file=build/datagen-classinit.log")
        }

        configureEach {
            jvmArguments = listOf(
                "-XX:+IgnoreUnrecognizedVMOptions",
                "-XX:+AllowEnhancedClassRedefinition"
            )
            systemProperty("forge.logging.markers", "REGISTRIES")
            logLevel = org.slf4j.event.Level.DEBUG
        }
    }

    mods {
        create(mod_id) {
            sourceSet(mainSourceSet)
        }
    }
}

// Include resources generated by data generators.
mainSourceSet.resources.srcDir("src/generated/resources")

// 'localRuntime' dependencies are available at runtime but not pulled by dependents of this mod.
// Kotlin DSL 无 Groovy 的 methodMissing 自动创建：localRuntime 需显式创建
val localRuntimeConfig = configurations.create("localRuntime")
configurations.named("runtimeClasspath") {
    extendsFrom(localRuntimeConfig)
}

dependencies {
    implementation("maven.modrinth:jade:26.0.9+neoforge")
    // GeckoLib overlay 适配仅编译期需要（运行时由 lynae/skirk 等模组传递提供 5.5.1， ModList.isLoaded 门控）
    compileOnly("com.geckolib:geckolib-neoforge-26.1.2:5.5.1")
}

val generateModMetadata = tasks.register<ProcessResources>("generateModMetadata") {
    val replaceProperties = mapOf(
        "minecraft_version" to minecraft_version,
        "minecraft_version_range" to minecraft_version_range,
        "neo_version" to neo_version,
        "mod_id" to mod_id,
        "mod_name" to mod_name,
        "mod_license" to mod_license,
        "mod_version" to mod_version,
        "mod_authors" to mod_authors,
        "mod_description" to mod_description
    )
    inputs.properties(replaceProperties)
    expand(replaceProperties)
    from("src/main/templates")
    into("build/generated/sources/modMetadata")
}
mainSourceSet.resources.srcDir(generateModMetadata)
neoForge.ideSyncTask(generateModMetadata)

publishing {
    publications {
        create<MavenPublication>("mavenJava") {
            from(components["java"])
        }
    }
    repositories {
        maven {
            url = uri(file("repo"))
        }
    }
}
publishMods {
    file.set(tasks.named<Jar>("jar").flatMap { it.archiveFile })

    type.set( BETA)
    modLoaders.add("neoforge")
    changelog.set("")
    curseforge {
        projectId.set("1255343")
        accessToken.set(providers.environmentVariable("CURSEFORGE_TOKEN"))
        minecraftVersions.add("26.1.2")
        client.set(true)

//        requires("fabric-api")
    }
    modrinth {
        projectId.set("euYoe1uE")
        accessToken.set(providers.environmentVariable("MODRINTH_TOKEN"))
        minecraftVersions.add("26.1.2")
    }

}
tasks.withType<JavaCompile>().configureEach {
    options.encoding = "UTF-8"
    options.compilerArgs.addAll(listOf("-Xmaxerrs", "10000", "-Xmaxwarns", "10000"))
}

idea {
    module {
        isDownloadSources = true
        isDownloadJavadoc = true
    }
}
